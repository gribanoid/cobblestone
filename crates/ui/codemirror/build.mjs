import { build } from "esbuild";
import { readFile } from "node:fs/promises";

const { packages } = JSON.parse(await readFile("package-lock.json", "utf8"));
const notices = await Promise.all(Object.entries(packages)
  .filter(([path, pkg]) => path && !pkg.dev)
  .map(async ([path, pkg]) => {
    const name = path.split("node_modules/").at(-1);
    const license = await readFile(path + "/LICENSE", "utf8");
    return `${name} ${pkg.version}\n${license.trim()}`;
  }));

await build({
  entryPoints: ["editor.js"],
  outfile: "editor.bundle.js",
  bundle: true,
  format: "iife",
  globalName: "CobblestoneCodeMirror",
  minify: true,
  legalComments: "none",
  banner: {
    js: "/*! Generated by npm run build. Bundled dependency licenses:\n\n" +
      notices.join("\n\n").replaceAll("*/", "* /") + "\n*/",
  },
  footer: { js: "globalThis.CobblestoneCodeMirror = CobblestoneCodeMirror;" },
});
